export type PolzaKey = keyof typeof ru
export type T = (key: PolzaKey, params?: Record<string, string | number>) => string
export const DICTIONARIES = { ru, en, zh: en }

export function resetLabel(t: T, reset: string | null): string {
  switch (reset) {
    case 'daily': return t('perDay')
    case 'weekly': return t('perWeek')
    case 'monthly': return t('perMonth')
    default: return t('total')
  }
}
